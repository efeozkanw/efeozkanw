export function glyph(char) {
  const entry = glyphs[char];
  if (!entry) {
    throw new Error(`No dot-matrix glyph for "${char}"`);
  }
  return Array.isArray(entry) ? { top: 0, rows: entry } : entry;
}

export function textWidth(text) {
  return [...text].reduce(
    (width, char, index) => width + glyph(char).rows[0].length + (index ? 1 : 0),
    0,
  );
}

export function textDots(text, column, row) {
  const dots = [];
  let x = column;
  for (const char of text) {
    const { top, rows } = glyph(char);
    rows.forEach((line, dy) => {
      [...line].forEach((cell, dx) => {
        if (cell === '#') {
          dots.push([x + dx, row + top + dy]);
        }
      });
    });
    x += rows[0].length + 1;
  }
  return dots;
}
